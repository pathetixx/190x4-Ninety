#!/usr/bin/env python3
"""Mirroring OTA artifacts to Cloudflare R2 — a fallback reachable from Russia.

GitHub serves releases from `release-assets.githubusercontent.com`, which is cut by
some Russian ISPs. R2 (via the neutral `pub-*.r2.dev`) is reachable from Russia and has no
egress fee. We upload the very same .exe (the minisign signature is the same → valid) and
a variant of latest.json with the url pointing to r2.dev. Current clients use GitLab and
GitHub; R2 is kept for old versions where it was the first endpoint.

Runs in CI after the github variant of latest.json is generated (it's already in CWD).
Credentials/settings come from env (see the build.yml step). Upload only; downloads are anonymous.
"""
import glob
import json
import os
import sys

import boto3

pub = os.environ["R2_PUBLIC_URL"].rstrip("/")
bucket = os.environ["R2_BUCKET"]
endpoint = os.environ["R2_ENDPOINT"]

exes = glob.glob("src-tauri/target/release/bundle/nsis/*-setup.exe")
if not exes:
    sys.exit("R2 mirror: NSIS setup .exe не найден")
exe = exes[0]
name = os.path.basename(exe)

# The github variant of latest.json was already generated by the previous step — we take it and change
# only the url to r2.dev (version/notes/pub_date/signature stay the same).
with open("latest.json", encoding="utf-8") as f:
    data = json.load(f)
data["platforms"]["windows-x86_64"]["url"] = f"{pub}/{name}"
with open("latest-r2.json", "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

s3 = boto3.client("s3", endpoint_url=endpoint, region_name="auto")
# .exe — a versioned name (not overwritten); latest.json — a stable key
# (always fresh, the endpoint looks at it).
s3.upload_file(exe, bucket, name, ExtraArgs={"ContentType": "application/octet-stream"})
s3.upload_file("latest-r2.json", bucket, "latest.json", ExtraArgs={"ContentType": "application/json"})
print(f"R2 mirror OK: {pub}/latest.json -> {name}")
